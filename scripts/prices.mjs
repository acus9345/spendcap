// Regenerates src/prices.ts from the models.dev catalog. Run with `npm run prices`.
import { writeFileSync } from "node:fs";

const PROVIDERS = ["openai", "anthropic", "google"];
const SKIP = /image|embedding|tts|live|realtime|lyria|gemma|deep-research|translate|computer-use/;

// models.dev differs from the provider's own price list here. The provider wins.
const OVERRIDES = {
  "claude-sonnet-5-5": { cacheRead: 0.2 },
};

const response = await fetch("https://models.dev/api.json");
if (!response.ok) throw new Error(`models.dev returned ${response.status}`);
const catalog = await response.json();

function fields(cost) {
  return {
    input: cost.input,
    output: cost.output,
    ...(cost.cache_read === undefined ? {} : { cacheRead: cost.cache_read }),
    ...(cost.cache_write === undefined ? {} : { cacheWrite: cost.cache_write }),
  };
}

const rows = [];
for (const provider of PROVIDERS) {
  for (const [id, model] of Object.entries(catalog[provider].models)) {
    const cost = model.cost;
    if (SKIP.test(id) || !cost?.input || !cost.output) continue;
    const tier = cost.tiers?.find((item) => item.tier?.type === "context");
    const price = {
      ...fields(cost),
      ...(tier ? { over: { tokens: tier.tier.size, ...fields(tier) } } : {}),
      ...OVERRIDES[id],
    };
    rows.push([id, price]);
  }
}
rows.sort(([a], [b]) => a.localeCompare(b));

const today = new Date().toISOString().slice(0, 10);
const body = rows.map(([id, price]) => `  ${JSON.stringify(id)}: ${JSON.stringify(price)},`).join("\n");
writeFileSync(
  new URL("../src/prices.ts", import.meta.url),
  `// Generated by scripts/prices.mjs. Do not edit by hand.
import type { Price } from "./types.js";

export const PRICES_AS_OF = "${today}";

/** USD per million tokens. */
export const PRICES: Record<string, Price> = {
${body}
};
`,
);
console.log(`${rows.length} models`);
